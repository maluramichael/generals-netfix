"""Generate GeneralsMD/.../Audio/AudioLengthTable.inl from the English Zero Hour data.

Usage (English install, ZH archives last so they override the Generals base):
  uv run --no-project python -I scripts/gen-audio-lengths.py \
    "<ZH>/ZH_Generals/AudioEnglish.big" "<ZH>/ZH_Generals/SpeechEnglish.big" \
    "<ZH>/AudioEnglishZH.big" "<ZH>/SpeechEnglishZH.big" > GeneralsMD/Code/GameEngine/Source/Common/Audio/AudioLengthTable.inl

Only WAVs inside an "English" folder are listed: those are the localized files whose length differs per language.
Key = FNV-1a 32 of the lower-case path without the language folder, e.g. data\\audio\\speech\\ttoxi001.wav.
"""
import struct
import sys

BS = chr(92)


def entries(path):
    with open(path, "rb") as f:
        head = f.read(16)
        if head[:4] not in (b"BIGF", b"BIG4"):
            raise SystemExit(f"not a BIG archive: {path}")
        count, = struct.unpack(">I", head[8:12])
        for _ in range(count):
            off, size = struct.unpack(">II", f.read(8))
            name = b""
            while (c := f.read(1)) != b"\0":
                name += c
            yield name.decode("latin-1"), off, size


def wav_ms(blob):
    if blob[:4] != b"RIFF" or blob[8:12] != b"WAVE":
        return None
    pos, fmt, fact, data = 12, None, None, None
    while pos + 8 <= len(blob):
        cid, clen = blob[pos:pos + 4], struct.unpack("<I", blob[pos + 4:pos + 8])[0]
        body = blob[pos + 8:pos + 8 + clen]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", body[:16])
        elif cid == b"fact":
            fact = struct.unpack("<I", body[:4])[0]
        elif cid == b"data":
            data = clen
        pos += 8 + clen + (clen & 1)
    if not fmt or data is None:
        return None
    tag, channels, rate, byterate, align, bits = fmt
    if tag == 1:
        return data * 1000 // byterate
    if fact:
        return fact * 1000 // rate
    if tag == 0x11 and align:  # IMA ADPCM without fact chunk
        per_block = (align - 4 * channels) * 8 // (4 * channels) + 1
        return (data // align) * per_block * 1000 // rate
    return data * 1000 // byterate


def fnv1a(text):
    h = 0x811C9DC5
    for b in text.encode("latin-1"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def main(bigs):
    table = {}
    for big in bigs:
        with open(big, "rb") as f:
            for name, off, size in list(entries(big)):
                parts = name.lower().split(BS)
                if not name.lower().endswith(".wav") or "english" not in parts:
                    continue
                f.seek(off)
                ms = wav_ms(f.read(size))
                if ms is None:
                    raise SystemExit(f"cannot read WAV header: {name}")
                key = BS.join(p for p in parts if p != "english")
                table[key] = ms
    hashes = {}
    for key in table:
        h = fnv1a(key)
        if h in hashes and hashes[h] != key:
            raise SystemExit(f"hash collision: {key} {hashes[h]}")
        hashes[h] = key
    print("// Generated by scripts/gen-audio-lengths.py from the English Zero Hour data. Do not edit.")
    print(f"// {len(table)} localized WAVs: FNV-1a 32 of the lower-case path without language folder, length in ms.")
    for h in sorted(hashes):
        print(f"{{ 0x{h:08X}u, {table[hashes[h]]}u }}, // {hashes[h].rsplit(BS, 1)[1]}")


def self_check():
    assert fnv1a("") == 0x811C9DC5
    assert fnv1a("a") == 0xE40C292C
    pcm = b"RIFF" + struct.pack("<I", 36 + 8000) + b"WAVE" + b"fmt " + struct.pack("<IHHIIHH", 16, 1, 1, 8000, 8000, 1, 8) + b"data" + struct.pack("<I", 8000) + bytes(8000)
    assert wav_ms(pcm) == 1000


if __name__ == "__main__":
    self_check()
    main(sys.argv[1:])
